export function textWidth(text: string, scale = 1, spacing = 1) {
  return text.length * (5 + spacing) * scale - spacing * scale
}

/** Draw 5×7 text with its top-left corner at (x, y). */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  spacing = 1,
) {
  ctx.fillStyle = color
  let cx = x
  for (const ch of text.toUpperCase()) {
    const glyph = FONT[ch] ?? FONT[' ']
    for (let r = 0; r < 7; r++)
      for (let c = 0; c < 5; c++) if (glyph[r][c] === '1') ctx.fillRect(cx + c * scale, y + r * scale, scale, scale)
    cx += (5 + spacing) * scale
  }
}
